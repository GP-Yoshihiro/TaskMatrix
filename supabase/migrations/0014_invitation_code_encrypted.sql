-- ============================================================
-- 招待コードを、あとから取り出せる形で保存する
--
-- ハッシュのみの保存では、発行直後の 1 回しかコードを見せられない。
-- 複数を発行して渡す運用では、過去のコードを読み返せないと立ち行かない。
--
-- 平文では保存しない。鍵をデータベースの外に置いて暗号化する
-- （Google のリフレッシュトークンと同じ仕組み）。
-- データベースのダンプが漏れても、鍵が無ければ復号できない。
--
-- 照合は引き続き code_hash で行う。こちらは復号を伴わないため速い。
-- ============================================================

alter table public.invitations
  add column if not exists code_encrypted text not null default '';

comment on column public.invitations.code_encrypted is
  '暗号化した招待コード。管理者が読み返すためだけに使う。照合には code_hash を使う';
